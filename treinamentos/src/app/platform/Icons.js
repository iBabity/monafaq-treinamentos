export function getCategoryIcon(cat) {
  if (!cat) return Icons.fiscal;
  
  const name = (cat.name || '').toLowerCase();
  
  // 1. Match by name first to override generic database defaults
  if (name.includes('apresentação') || name.includes('cadastro')) {
    if (name.includes('produto')) {
      return Icons.cadastroProdutos;
    }
    return Icons.cadastros;
  }
  if (name.includes('compra') || name.includes('faturamento')) {
    return Icons.compras;
  }
  if (name.includes('financeiro')) {
    return Icons.financeiro;
  }
  if (name.includes('fiscal')) {
    return Icons.fiscal;
  }
  if (name.includes('contabilidade') || name.includes('caixa')) {
    return Icons.contabilidade;
  }
  if (name.includes('operacional') || name.includes('gerencial')) {
    return Icons.operacional;
  }
  if (name.includes('pdv')) {
    return Icons.pdv;
  }
  if (name.includes('sincdata') || name.includes('sinc') || name.includes('data')) {
    return Icons.sincdata;
  }
  if (name.includes('extra')) {
    return Icons.extra;
  }

  // 2. If no name matched, try using the database-configured icon if it is not a generic 'fiscal' default
  if (cat.icon && cat.icon !== 'fiscal' && Icons[cat.icon]) {
    return Icons[cat.icon];
  }

  // 3. Fallback
  return Icons.fiscal;
}
